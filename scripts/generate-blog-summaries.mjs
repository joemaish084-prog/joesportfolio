// Keep the editorial source in one place, but don't ship article bodies to
// listing, topic, related-post or case-study cards. No source code is executed.
import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";

const source = fs.readFileSync("src/data/blogPosts.ts", "utf8");
const file = ts.createSourceFile("blogPosts.ts", source, ts.ScriptTarget.Latest, true);
const imports = file.statements.filter(node => ts.isImportDeclaration(node) && !node.importClause?.isTypeOnly);
const declaration = file.statements.flatMap(node => ts.isVariableStatement(node) ? [...node.declarationList.declarations] : [])
  .find(node => node.name.getText(file) === "blogPosts");
assert(declaration && ts.isArrayLiteralExpression(declaration.initializer), "Expected a literal blogPosts array");
const omitted = new Set(["intro", "sections", "heroVisual"]);
const posts = declaration.initializer.elements.map(node => {
  assert(ts.isObjectLiteralExpression(node), "Blog summaries require literal post objects");
  const properties = node.properties.filter(property => {
    assert(ts.isPropertyAssignment(property), "Unexpected post property");
    return !omitted.has(property.name.getText(file));
  });
  return `  {\n${properties.map(property => `    ${property.getText(file)},`).join("\n")}\n  }`;
});
const output = `// Generated by scripts/generate-blog-summaries.mjs. Edit blogPosts.ts instead.\n`
  + `import type { BlogPost } from "./blogPosts";\n`
  + imports.map(node => node.getText(file)).join("\n")
  + `\n\nexport type BlogSummary = Omit<BlogPost, "intro" | "sections" | "heroVisual">;\n`
  + `export const blogSummaries: BlogSummary[] = [\n${posts.join(",\n")}\n];\n`;
fs.writeFileSync("src/data/blogSummaries.ts", output);
console.log(`Generated ${posts.length} blog summaries without article bodies.`);
