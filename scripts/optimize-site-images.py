"""Generate responsive WebP copies; originals stay untouched. Requires Pillow."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'site-review.local/image-tools'))
from PIL import Image, ImageOps

sources = [
    'src/assets/longform-asdsp.webp',
    'src/assets/joseph-maina-portrait.webp',
    'src/assets/short-maji-ni-uhai.webp',
    'src/assets/design-iclear-engineered.webp',
    'src/assets/convey-podcast-thumbnail.webp',
    'src/assets/short-iclear-dishwash.webp',
    'src/assets/branding/iclear/logo-horizontal-white.webp',
    'src/assets/branding/duara/logo-horizontal.webp',
    'src/assets/csr-baobab-group-photo.webp',
    'src/assets/csr-baobab-installed-units.webp',
    'src/assets/csr-baobab-handover.webp',
    'src/assets/csr-baobab-team-hoodie.webp',
    'public/logo/jm-lockup.png',
]
imports = []
entries = []
for index, source in enumerate(sources):
    original = ROOT / source
    with Image.open(original) as opened:
        image = ImageOps.exif_transpose(opened)
        width, height = image.size
        variants = []
        for requested in (240, 480, 960):
            target_width = min(requested, width)
            if any(item[0] == target_width for item in variants):
                continue
            resized = image.resize((target_width, round(height * target_width / width)), Image.Resampling.LANCZOS)
            if source.startswith('public/'):
                target = original.with_name(f'{original.stem}-{target_width}.webp')
                url = '/' + target.relative_to(ROOT / 'public').as_posix()
                name = repr(url)
            else:
                target = ROOT / 'src/assets/responsive' / f'{index}-{original.stem}-{target_width}.webp'
                name = f'image{index}_{target_width}'
                imports.append(f'import {name} from "@/assets/{target.relative_to(ROOT / "src/assets").as_posix()}";')
            target.parent.mkdir(parents=True, exist_ok=True)
            resized.save(target, 'WEBP', quality=80, method=6)
            variants.append((target_width, name))
        if source.startswith('public/'):
            key = repr('/' + original.relative_to(ROOT / 'public').as_posix())
        else:
            key = f'original{index}'
            imports.append(f'import {key} from "@/assets/{original.relative_to(ROOT / "src/assets").as_posix()}";')
        default = variants[min(1, len(variants) - 1)][1]
        srcset = ', '.join('${' + name + '} ' + str(w) + 'w' for w, name in variants)
        entries.append(f'  [{key}, {{ src: {default}, srcSet: `{srcset}`, width: {width}, height: {height} }}],')
        print(f'{original.name}: {original.stat().st_size} bytes; smallest variant {variants[0][0]}px')

module = '\n'.join(imports) + '\n\nconst variants = new Map<string, {src: string; srcSet: string; width: number; height: number}>([\n' + '\n'.join(entries) + '\n]);\n\n'
module += 'export function localImageProps(src: string, sizes: string) {\n  const image = variants.get(src);\n  return image ? { ...image, sizes } : {};\n}\n'
(ROOT / 'src/lib/imageVariants.ts').write_text('// Generated by scripts/optimize-site-images.py.\n' + module, encoding='utf-8')
